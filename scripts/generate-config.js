// scripts/generate-config.js
// ---------------------------------------------------------------------
// A static website can't read .env files, so this script copies the two
// PUBLIC values (project URL + anon/publishable key) from .env into
// config.js, which index.html loads.
//
//   node scripts/generate-config.js
//
// The anon key is designed to be public: it only gives the permissions
// that our RLS policies and grants allow. The SERVICE ROLE key must
// never reach the browser, so we refuse to write it.
// ---------------------------------------------------------------------

const fs = require("fs");
const path = require("path");
const { loadEnv, requireVars } = require("./env");

// Returns true if a key is a secret/service key that bypasses RLS.
function isSecretKey(key) {
  if (key.startsWith("sb_secret_")) return true;
  const parts = key.split(".");
  if (parts.length === 3) {
    try {
      const payload = JSON.parse(Buffer.from(parts[1], "base64url").toString("utf8"));
      return payload.role === "service_role";
    } catch (error) {
      return false;
    }
  }
  return false;
}

const env = loadEnv();
requireVars(env, ["SUPABASE_URL", "SUPABASE_ANON_KEY"]);

if (isSecretKey(env.SUPABASE_ANON_KEY)) {
  console.error("STOP: SUPABASE_ANON_KEY looks like a SERVICE ROLE / secret key.");
  console.error("Use the 'anon public' (or 'publishable') key from Project Settings -> API.");
  process.exit(1);
}

const output =
  "// config.js — GENERATED by scripts/generate-config.js from .env (public values only).\n" +
  "// Only public values belong here. Security is enforced by RLS in the database.\n" +
  "window.APP_CONFIG = " +
  JSON.stringify({ SUPABASE_URL: env.SUPABASE_URL, SUPABASE_ANON_KEY: env.SUPABASE_ANON_KEY }, null, 2) +
  ";\n";

fs.writeFileSync(path.join(__dirname, "..", "config.js"), output);
console.log("Wrote config.js for " + env.SUPABASE_URL);
